public class MathOps{
    public static void main(String[]args){
        System.out.println("The max is :" + Math.max(3,4));
        System.out.println("The min is :" + Math.min(3,4));
        System.out.println("The power is :" + Math.pow(3,4));
        System.out.println("The absolute value is :" + Math.abs(- 3.4));
        System.out.println("The square root  is :" + Math.sqrt(39));
    }
}