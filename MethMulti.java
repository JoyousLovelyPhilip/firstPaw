public class multi{
    static void MultiPara(String name, int age){
        System.out.println(name + " is "+ age+ " years old");
    }
    public static void main(String[] args){
        MultiPara("Joy", 19);
        MultiPara("Annet", 20);
        MultiPara("Amma", 45);
        MultiPara("Appa",46);
    }
}