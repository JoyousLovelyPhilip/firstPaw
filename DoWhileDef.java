public class dowhileDef{
    public static void main(String[] args){
        int i = 0;
        do{
            System.out.println(i);
            i++;//The do/while loop is a variant of the while loop. This loop will execute the code block once, before checking if the condition is true. Then it will repeat the loop as long as the condition is true
        }
        while(i < 5);//The semicolon ; after the while condition is required!
    }

}